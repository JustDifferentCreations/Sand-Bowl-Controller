// === I2C Bit-Bang Configuration ===
#define SDA_PIN   2
#define SCL_PIN   3

#define SDA_HIGH() (PORTA.OUTSET = (1 << SDA_PIN))
#define SDA_LOW()  (PORTA.OUTCLR = (1 << SDA_PIN))
#define SCL_HIGH() (PORTA.OUTSET = (1 << SCL_PIN))
#define SCL_LOW()  (PORTA.OUTCLR = (1 << SCL_PIN))

#define SDA_OUTPUT() (PORTA.DIRSET = (1 << SDA_PIN))
#define SDA_INPUT()  (PORTA.DIRCLR = (1 << SDA_PIN))
#define SCL_OUTPUT() (PORTA.DIRSET = (1 << SCL_PIN))

#define SSD1306_I2C_DELAY() _delay_us(5)


